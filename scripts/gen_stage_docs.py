"""Generate ``docs/STAGES.md`` from the live registry.

Docs that are typed by hand drift from the code within a week. This script reads
the registry (the same metadata the runner validates against) and writes the
stage reference, so ``imgen stages`` and the documentation can never disagree.

    python scripts/gen_stage_docs.py            # writes docs/STAGES.md
    python scripts/gen_stage_docs.py --check    # exit 1 if the file is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "STAGES.md"

# Running this file as a script puts scripts/ on sys.path, not the repository root.
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


def render() -> str:
    from imgen.config import load_tools
    from imgen.registry import all_stages, load_builtin_stages

    load_builtin_stages()  # importing imgen alone does not register anything
    tools = load_tools()
    lines = [
        "# Stage reference",
        "",
        "<!-- generated by scripts/gen_stage_docs.py — do not edit by hand -->",
        "",
        f"{len(all_stages())} stages are registered. A pipeline is an ordered list of these; the",
        "runner validates the plane chain (`imgen validate pipelines/x.json`) before running.",
        "",
        "**Planes**: `rgb` (sRGB [0,1]) → `semantic` (scene-linear highlight field) →",
        "`highlight` ([0,1] resolved light fraction) → `nits` (cd/m²) → `scrgb` (1.0 = 80 cd/m²).",
        "",
        "## Summary",
        "",
        "| stage | kind | requires | produces | needs | description |",
        "|---|---|---|---|---|---|",
    ]
    for spec in all_stages():
        summary = spec.summary.replace("|", "\\|")
        lines.append(
            f"| `{spec.name}` | {spec.kind} | {', '.join(spec.requires) or '—'} | "
            f"{', '.join(spec.produces) or '—'} | {', '.join(spec.needs) or '—'} | {summary} |"
        )
    lines += ["", "## Parameters", ""]
    for spec in all_stages():
        lines.append(f"### `{spec.name}`")
        lines.append("")
        for line in (spec.doc or "").strip().splitlines():
            lines.append(line.strip())
        lines.append("")
        lines.append(f"- **kind**: {spec.kind}")
        lines.append(f"- **requires**: {', '.join(spec.requires) or '(nothing)'}")
        lines.append(f"- **produces**: {', '.join(spec.produces) or '(nothing — sink)'}")
        lines.append(f"- **external**: {', '.join(spec.needs) or '(none)'}")
        lines.append("")
        if spec.params:
            lines.append("| parameter | default |")
            lines.append("|---|---|")
            for key, value in spec.params.items():
                lines.append(f"| `{key}` | `{value!r}` |")
        else:
            lines.append("_No parameters._")
        lines.append("")
    lines += [
        "## Resolved tools on this machine",
        "",
        "| tool | path |",
        "|---|---|",
    ]
    for name, path in (
        ("realesrgan", tools.realesrgan),
        ("realcugan", tools.realcugan),
        ("waifu2x", tools.waifu2x),
        ("ffmpeg", tools.ffmpeg),
        ("jxr-encode-wic", tools.jxr_encode),
        ("jxr-inspect", tools.jxr_inspect),
        ("verify-jxr", tools.jxr_verify),
        ("models dir", tools.models_dir),
        ("python (semantic stage)", tools.python),
    ):
        lines.append(f"| {name} | `{path or '— not found —'}` |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="regenerate docs/STAGES.md from the registry")
    parser.add_argument("--check", action="store_true", help="fail if the file on disk differs")
    parser.add_argument("--out", default=str(TARGET))
    args = parser.parse_args(argv)

    content = render()
    target = Path(args.out)
    if args.check:
        existing = target.read_text(encoding="utf-8") if target.is_file() else ""
        if existing != content:
            print(f"{target} is stale — run `python scripts/gen_stage_docs.py`")
            return 1
        print(f"{target} is up to date")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    print(f"wrote {target} ({content.count(chr(10)) + 1} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
